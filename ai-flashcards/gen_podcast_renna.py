def cache_key(text: str, voice: str) -> Path:
    import hashlib
    h = hashlib.sha256(f"{TTS_MODEL}|{voice}|{SAMPLE_RATE}|{text}".encode()).hexdigest()[:24]
    return CACHE_DIR / f"{h}.wav"


def tts_one(client, key: str, text: str, voice_id: str, dest: Path) -> bool:
    """合成单轮。命中缓存返回 False（未计费），实际请求返回 True。"""
    cached = cache_key(text, voice_id)
    if cached.exists() and cached.stat().st_size > 1000:
        dest.write_bytes(cached.read_bytes())
        return False

    body = {
        "text": text,
        "reference_id": voice_id,
        "format": "wav",
        "sample_rate": SAMPLE_RATE,
        "latency": "normal",
        "normalize": True,
        "temperature": 0.55,
        "top_p": 0.7,
        "chunk_length": 300,
        "prosody": {"speed": 1, "volume": 0, "normalize_loudness": True},
    }
    last_err = None
    for attempt in range(4):
        try:
            res = client.post(
                TTS_URL,
                headers={"Authorization": f"Bearer {key}", "Content-Type": "application/json",
                         "model": TTS_MODEL},
                json=body, timeout=180.0,
            )
            if res.status_code == 429:
                wait = 8 * (attempt + 1)
                print(f"    429，等 {wait}s", flush=True)
                time.sleep(wait)
                continue
            if res.status_code >= 400:
                raise RuntimeError(f"HTTP {res.status_code}: {res.text[:300]}")
            if len(res.content) < 1000 or res.content[:4] != b"RIFF":
                raise RuntimeError(f"返回不是 wav: {len(res.content)} bytes")
            CACHE_DIR.mkdir(parents=True, exist_ok=True)
            cached.write_bytes(res.content)
            dest.write_bytes(res.content)
            return True
        except Exception as e:
            last_err = e
            wait = 4 * (attempt + 1)
            print(f"    重试 {attempt + 1}: {e}  等 {wait}s", flush=True)
            time.sleep(wait)
    raise RuntimeError(last_err)


def concat_wavs(parts: list[Path], dest: Path, gaps: list[float]) -> None:
    import wave
    with wave.open(str(parts[0]), "rb") as first:
        params = first.getparams()
        frames = [first.readframes(first.getnframes())]
    bpf = params.nchannels * params.sampwidth

    def silence(sec: float) -> bytes:
        return b"\x00" * (max(0, int(params.framerate * sec)) * bpf)

    for i, p in enumerate(parts[1:], 1):
        frames.append(silence(gaps[i - 1]))
        with wave.open(str(p), "rb") as w:
            if (w.getnchannels(), w.getsampwidth(), w.getframerate()) != (
                params.nchannels, params.sampwidth, params.framerate):
                raise RuntimeError(f"wav 参数不一致: {p.name}")
            frames.append(w.readframes(w.getnframes()))
    with wave.open(str(dest), "wb") as out:
        out.setparams(params)
        out.writeframes(b"".join(frames))


def wav_to_mp3(wav_path: Path, mp3_path: Path) -> None:
    subprocess.check_call([LAME, "--silent", "-b", "64", "-m", "m", str(wav_path), str(mp3_path)])


def generate(only: set[int] | None, force: bool, workers: int) -> None:
    import httpx
    from concurrent.futures import ThreadPoolExecutor, as_completed
    lock = threading.Lock()
    key = load_api_key()
    AUDIO_DIR.mkdir(parents=True, exist_ok=True)
    nums = [n for n in sorted(EPISODES) if not only or n in only]
    billed = hits = 0
    limits = httpx.Limits(max_connections=workers, max_keepalive_connections=workers)
    with httpx.Client(limits=limits) as client:
        for n in nums:
            e = EPISODES[n]
            dest = ROOT / e["audio"]
            if not force and dest.exists() and dest.stat().st_size > 10_000:
                print(f"skip {dest.name}（已存在）", flush=True)
                continue
            turns = e["turns"]
            print(f"ep {n:02d}  {len(turns)} 轮 / {sum(len(t['t']) for t in turns)} 字 -> {dest.name}", flush=True)
            with tempfile.TemporaryDirectory() as td:
                parts = [Path(td) / f"{i:03d}.wav" for i in range(1, len(turns) + 1)]

                def synth(i: int) -> bool:
                    turn = turns[i]
                    voice = HOST_VOICE if turn["s"] == "host" else GUEST_VOICE
                    t0 = time.time()
                    fresh = tts_one(client, key, turn["t"], voice, parts[i])
                    with lock:
                        done[0] += 1
                        tag = "API" if fresh else "缓存"
                        print(f"  {done[0]}/{len(turns)} #{i+1:03d} {turn['s']:<5} "
                              f"{len(turn['t']):>3}字 [{tag}] {time.time()-t0:.1f}s", flush=True)
                    return fresh

                done = [0]
                with ThreadPoolExecutor(max_workers=workers) as pool:
                    futs = {pool.submit(synth, i): i for i in range(len(turns))}
                    for fut in as_completed(futs):
                        fresh = fut.result()   # 任一轮彻底失败则整集中止，不产出残缺音频
                        billed += fresh; hits += (not fresh)

                missing = [p for p in parts if not p.exists() or p.stat().st_size < 1000]
                if missing:
                    raise RuntimeError(f"ep {n} 有 {len(missing)} 轮未产出 wav")
                gaps = [GAP_SAME_SEC if a["s"] == b["s"] else GAP_SWITCH_SEC
                        for a, b in zip(turns, turns[1:])]
                wav_out = Path(td) / "episode.wav"
                concat_wavs(parts, wav_out, gaps)
                wav_to_mp3(wav_out, dest)
                total = annotate(n, parts)
                write_lrc(n)
            print(f"  saved {dest.name} ({dest.stat().st_size} bytes, "
                  f"{total // 60000}:{total // 1000 % 60:02d}) + {lrc_path(n).name}", flush=True)
    print(f"\n  本次实际调用 API {billed} 次，命中缓存 {hits} 次")
    dump_json()   # 把新算出的时间轴写回 json


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--only", default="", help="逗号分隔的集数")
    ap.add_argument("--concurrency", type=int, default=CONCURRENCY,
                    help=f"每集内并发合成的轮数（默认 {CONCURRENCY}）")
    ap.add_argument("--dry-run", action="store_true", help="只体检和预估，不写文件、不调 API")
    ap.add_argument("--json-only", action="store_true", help="只写 json")
    ap.add_argument("--sync-only", action="store_true",
                    help="只用缓存补时间轴并写 json/lrc，不调 API")
    ap.add_argument("--force", action="store_true", help="覆盖已有 mp3")
    ap.add_argument("--host-voice", default="")
    ap.add_argument("--guest-voice", default="")
    args = ap.parse_args()

    global HOST_VOICE, GUEST_VOICE
    if args.host_voice: HOST_VOICE = args.host_voice.strip()
    if args.guest_voice: GUEST_VOICE = args.guest_voice.strip()

    print("=== 讲稿体检")
    lint(strict=not args.dry_run)
    print("\n=== 规模")
    stats()

    if args.dry_run:
        print("\n  --dry-run：未写任何文件，未调用 API")
        return

    print()
    n_sync = annotate_from_cache()
    if n_sync:
        print(f"  时间轴：{n_sync}/{len(EPISODES)} 集已由缓存算出")
    dump_json()
    wrote = [write_lrc(n) for n in sorted(EPISODES)]
    print(f"  LRC：写出 {sum(w is not None for w in wrote)} 份")
    if args.json_only or args.sync_only:
        return
    only = {int(x) for x in args.only.split(",") if x.strip()} if args.only else None
    generate(only, force=args.force, workers=args.concurrency)


if __name__ == "__main__":
    main()
