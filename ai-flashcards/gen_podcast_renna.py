def load_api_key() -> str:
    if not ENV_FILE.exists():
        sys.exit("缺少 .env（FISH_KEY=...）")
    for line in ENV_FILE.read_text().splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        k, v = line.split("=", 1)
        if k.strip() in ("FISH_KEY", "FISH_API_KEY"):
            return v.strip().strip('"').strip("'")
    sys.exit(".env 里没有 FISH_KEY")


def turn_offsets(wavs: list[Path], turns: list[dict]) -> tuple[list[int], int]:
    """按 concat_wavs 的拼接方式精确算出每轮的起始毫秒。

    concat 是采样级拼接，静音长度用 int(framerate * sec) 帧，
    这里用同样的整数运算，结果与最终 wav 逐帧一致。
    """
    import wave
    off, frames = [], 0
    for i, (w, turn) in enumerate(zip(wavs, turns)):
        off.append(round(frames * 1000 / SAMPLE_RATE))
        with wave.open(str(w), "rb") as f:
            if f.getframerate() != SAMPLE_RATE:
                raise RuntimeError(f"采样率不符: {w.name}")
            # Fish Audio 返回流式 wav，头里 nframes 是占位符（0x7FFFFF80），
            # 只能按实际读到的字节数算。concat_wavs 同样是读到 EOF，两者一致。
            n = len(f.readframes(f.getnframes())) // (f.getnchannels() * f.getsampwidth())
            if n == 0:
                raise RuntimeError(f"空 wav: {w.name}")
            frames += n
        if i + 1 < len(turns):
            gap = GAP_SAME_SEC if turns[i + 1]["s"] == turn["s"] else GAP_SWITCH_SEC
            frames += int(SAMPLE_RATE * gap)
    return off, round(frames * 1000 / SAMPLE_RATE)


def annotate(n: int, wavs: list[Path]) -> int:
    """把时间轴写进 turns（字段 ms），返回总时长毫秒。"""
    turns = EPISODES[n]["turns"]
    off, total = turn_offsets(wavs, turns)
    for turn, ms in zip(turns, off):
        turn["ms"] = ms
    EPISODES[n]["ms"] = total
    return total


def annotate_from_cache() -> int:
    """用 .tts-cache 里的分句 wav 补时间轴，不调 API。返回补齐的集数。"""
    done = 0
    for n in sorted(EPISODES):
        turns = EPISODES[n]["turns"]
        wavs = [cache_key(t["t"], HOST_VOICE if t["s"] == "host" else GUEST_VOICE)
                for t in turns]
        if not all(w.exists() and w.stat().st_size > 1000 for w in wavs):
            continue
        annotate(n, wavs)
        done += 1
    return done


def lrc_path(n: int) -> Path:
    return (ROOT / EPISODES[n]["audio"]).with_suffix(".lrc")


def write_lrc(n: int) -> Path | None:
    """导出 LRC。没有时间轴就跳过。"""
    e = EPISODES[n]
    turns = e["turns"]
    if any("ms" not in t for t in turns):
        return None
    lines = [f"[ti:第 {n} 集 {e['title']}]",
             f"[ar:{HOST_NAME} & {GUEST_NAME}]",
             f"[al:{SERIES}]", "[by:gen_podcast_renna.py]", ""]
    for t in turns:
        cs = t["ms"] // 10
        mm, rest = divmod(cs, 6000)
        name = HOST_NAME if t["s"] == "host" else GUEST_NAME
        lines.append(f"[{mm:02d}:{rest // 100:02d}.{rest % 100:02d}]{name}：{t['t']}")
    dest = lrc_path(n)
    dest.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return dest


