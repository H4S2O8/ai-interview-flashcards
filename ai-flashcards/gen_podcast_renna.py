META_PATTERNS = [
    (r"不用再回去翻原文|不必再翻原文|不用看原文|替代阅读", "把节目定位当台词说了"),
    (r"听众看不到|听不到|音频里|这档节目的目标|这一季的目标", "点破媒介限制或制作意图"),
    (r"你口述一下|念一下代码|读一下这段代码", "像给嘉宾的导演指令"),
]


def lint(strict: bool = False) -> int:
    """检查讲稿里有没有把制作意图写进台词。返回问题数。"""
    problems = 0
    for n in sorted(EPISODES):
        for i, turn in enumerate(EPISODES[n]["turns"]):
            for pat, why in META_PATTERNS:
                if re.search(pat, turn["t"]):
                    problems += 1
                    print(f"  ✗ ep{n:02d} 第 {i} 轮 [{turn['s']}] {why}")
                    print(f"      {turn['t'][:60]}")
    print("  ✓ 讲稿体检通过，无越界台词" if not problems else f"  共 {problems} 处")
    if problems and strict:
        sys.exit("讲稿体检未通过")
    return problems


def stats() -> None:
    print(f"{'集':>3}{'轮次':>6}{'字数':>7}{'时长':>8}   标题")
    tt = tc = 0
    for n in sorted(EPISODES):
        e = EPISODES[n]
        c = sum(len(t["t"]) for t in e["turns"])
        tt += len(e["turns"]); tc += c
        print(f"{n:>3}{len(e['turns']):>6}{c:>7}{c / CHARS_PER_MIN:>7.1f}m   {e['title'][:30]}")
    print(f"\n  合计 {len(EPISODES)} 集 / {tt} 轮 / {tc} 字 / 约 {tc / CHARS_PER_MIN:.0f} 分钟")
    print(f"  TTS 请求数 = 轮次数 = {tt}（每轮一次，失败可命中缓存不重复计费）")


